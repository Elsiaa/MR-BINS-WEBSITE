  function applyLang(lang) {
    var dict = lang === "es" ? ES : null;
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    var n;
    while ((n = walker.nextNode())) {
      var p = n.parentElement;
      if (!p || p.closest("script,style")) continue;
      if (dict) {
        if (n.__en === undefined) n.__en = n.nodeValue;
        var key = n.__en.replace(/\s+/g, " ").trim();
        if (dict[key]) {
          n.nodeValue = n.__en.replace(key.replace(/ /g, " "), dict[key]);
          if (n.nodeValue.replace(/\s+/g, " ").trim() === key) n.nodeValue = dict[key];
        }
      } else if (n.__en !== undefined) {
        n.nodeValue = n.__en;
      }
    }
    document.querySelectorAll("[placeholder]").forEach(function (el) {
      if (el.__enph === undefined) el.__enph = el.getAttribute("placeholder");
      var k = el.__enph.trim();
      el.setAttribute("placeholder", dict && dict[k] ? dict[k] : el.__enph);
    });
    document.documentElement.lang = lang;
    var b = document.getElementById("langBtn");
    if (b) b.textContent = lang === "es" ? "EN" : "ES";
    try {
      localStorage.setItem("mrb_lang", lang);
    } catch (e) {}
    current = lang;
  }

